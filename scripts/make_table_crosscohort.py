"""Table: the cross-cohort test and its checks, for every model.

Each row is one version of the test of models fitted on gaitpdb and applied once
to WearGait-PD: the main test (the five gait features of D-013 at D-012's contact
threshold), four variants of the inputs, the contact threshold fixed at 20 N
(D-012's sensitivity analysis), and the two subsets of the test participants
(the one site with both groups, and the pairs matched on sex and age). Reads
results/crosscohort_results.csv and results/fixed_20N/crosscohort_results.csv
(scripts/run_cross_cohort.py) and writes results/crosscohort_table.csv and
results/crosscohort_table.md.

    python scripts/make_table_crosscohort.py [--results results]
"""

from __future__ import annotations

import argparse
from pathlib import Path

import pandas as pd

FAMILIES = ("logreg", "svm", "rf")
FAMILY_LABEL = {
    "logreg": "Logistic regression",
    "svm": "Support vector machine",
    "rf": "Random forest",
}
ROWS = [  # (row label, results folder, analysis, inputs)
    ("Main test: five gait features", "", "cross-cohort", "gait"),
    (
        "Each dataset's inputs standardised",
        "",
        "cross-cohort",
        "gait, standardised within dataset",
    ),
    (
        "Without the two variability features",
        "",
        "cross-cohort",
        "gait without variability",
    ),
    (
        "Robust variability in place of the CV",
        "",
        "cross-cohort",
        "gait, robust variability",
    ),
    ("Age and sex added", "", "cross-cohort", "gait + covariates"),
    ("Contact threshold fixed at 20 N", "fixed_20N", "cross-cohort", "gait"),
    (
        "VA Puget Sound only (both groups)",
        "",
        "cross-cohort, VA Puget Sound only",
        "gait",
    ),
    ("Pairs matched on sex and age", "", "cross-cohort, age-matched", "gait"),
]


def auc_ci(r: pd.Series) -> str:
    return f"{r['auc']:.3f} ({r['auc_low']:.3f} to {r['auc_high']:.3f})"


def build(results: Path) -> pd.DataFrame:
    files = {
        "": pd.read_csv(results / "crosscohort_results.csv"),
        "fixed_20N": pd.read_csv(results / "fixed_20N" / "crosscohort_results.csv"),
    }
    families = [f for f in FAMILIES if (files[""]["model"] == f).any()]
    out = []
    for label, folder, analysis, inputs in ROWS:
        table = files[folder]
        row = {"Version of the test": label}
        ns = set()
        for fam in families:
            hit = table[
                (table["analysis"] == analysis)
                & (table["inputs"] == inputs)
                & (table["model"] == fam)
            ]
            if len(hit) != 1:
                where = results / folder / "crosscohort_results.csv"
                raise SystemExit(
                    f"expected one row for {fam}, '{analysis}', '{inputs}' in {where}, "
                    f"found {len(hit)}"
                )
            r = hit.iloc[0]
            ns.add((int(r["n"]), int(r["n_pd"])))
            row[FAMILY_LABEL[fam]] = auc_ci(r)
        if len(ns) != 1:
            raise SystemExit(
                f"'{label}': the models were tested on different participants"
            )
        n, n_pd = ns.pop()
        row = {
            "Version of the test": label,
            "WearGait-PD participants (PD)": f"{n} ({n_pd})",
            **{k: v for k, v in row.items() if k != "Version of the test"},
        }
        out.append(row)
    return pd.DataFrame(out)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--results", default="results")
    args = ap.parse_args()
    results = Path(args.results)
    table = build(results)
    table.to_csv(results / "crosscohort_table.csv", index=False)
    caption = (
        "AUC (95% participant-bootstrap interval) of each model fitted on gaitpdb "
        "and applied once to WearGait-PD, for the main test and each check of it. "
        "Standardised: each input centred and scaled within its own dataset. "
        "Variability features: stride-time and swing-time CV; robust variability: "
        "their median-absolute-deviation versions. 20 N: the cleaning, features and "
        "models rerun at a fixed contact threshold (D-012's sensitivity analysis), "
        "which admits fewer WearGait-PD participants. Generated by "
        "scripts/make_table_crosscohort.py from results/crosscohort_results.csv and "
        "results/fixed_20N/crosscohort_results.csv."
    )
    with open(results / "crosscohort_table.md", "w", encoding="utf-8") as f:
        f.write(caption + "\n\n" + table.to_markdown(index=False) + "\n")
    print(table.to_string(index=False))


if __name__ == "__main__":
    main()
